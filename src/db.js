// שכבת הנתונים: Postgres.
// עם DATABASE_URL - מתחבר למסד בענן (Supabase). בלי - מסד מקומי בתיקיית data (PGlite),
// כך שאפשר להריץ ולבדוק על המחשב בלי שום הגדרה.
import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export const AGE_GROUPS = [
  'גיל הרך (0–3)',
  'גן (3–6)',
  'ראשית קריאה (6–9)',
  'ילדים (9–12)',
  'נוער',
  'מבוגרים',
  'לכל הגילאים',
];

const DEFAULT_CATEGORIES = ['ספרי קודש', 'ספרי ילדים', 'ספרי נוער', 'סיפורת', 'עיון', 'בישול'];

export class LibraryError extends Error {
  constructor(message, status = 400) {
    super(message);
    this.status = status;
  }
}

/** נרמול לצורך השוואה: בלי ניקוד, בלי גרשיים וסימני פיסוק, רווחים אחידים. */
export function normalize(s) {
  return String(s ?? '')
    .normalize('NFKC')
    .replace(/[֑-ׇ]/g, '')
    .replace(/["'`׳״.,:;!?()\-־–—]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/** התאריך של היום לפי שעון ישראל (השרת בענן רץ ב-UTC). */
export function today() {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: process.env.TZ_NAME ?? 'Asia/Jerusalem',
  }).format(new Date());
}

function cleanDate(value) {
  if (value == null || value === '') return today();
  const s = String(value).trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s) || Number.isNaN(Date.parse(s))) {
    throw new LibraryError('תאריך לא תקין. יש לכתוב בתבנית YYYY-MM-DD');
  }
  return s;
}

function cleanText(value, label, { required = false, max = 200 } = {}) {
  const s = String(value ?? '').replace(/\s+/g, ' ').trim();
  if (required && !s) throw new LibraryError(`חסר ${label}`);
  if (s.length > max) throw new LibraryError(`${label} ארוך מדי`);
  return s;
}

// הטבלאות נוצרות אוטומטית בהפעלה הראשונה. RLS מופעל בלי שום policy, כדי שהטבלאות
// לא יהיו נגישות דרך ה-API הציבורי של Supabase; האפליקציה מתחברת כבעלת הטבלאות.
const SCHEMA = `
  CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
  );
  CREATE TABLE IF NOT EXISTS books (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    author TEXT NOT NULL DEFAULT '',
    category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
    age_group TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE TABLE IF NOT EXISTS loans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    borrower TEXT NOT NULL,
    loaned_at TEXT NOT NULL,
    returned_at TEXT
  );
  CREATE UNIQUE INDEX IF NOT EXISTS one_open_loan_per_book
    ON loans(book_id) WHERE returned_at IS NULL;
  CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT);
  ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
  ALTER TABLE books ENABLE ROW LEVEL SECURITY;
  ALTER TABLE loans ENABLE ROW LEVEL SECURITY;
  ALTER TABLE meta ENABLE ROW LEVEL SECURITY;
`;

const BOOK_SELECT = `
  SELECT b.id, b.title, b.author, b.category_id AS "categoryId", c.name AS category,
         b.age_group AS "ageGroup", b.notes,
         l.id AS "loanId", l.borrower, l.loaned_at AS "loanedAt"
  FROM books b
  LEFT JOIN categories c ON c.id = b.category_id
  LEFT JOIN loans l ON l.book_id = b.id AND l.returned_at IS NULL`;

/** חיבור למסד. מחזיר { q(sql, params) -> rows, exec(sql), close() }. */
async function connect(target) {
  if (target && /^postgres(ql)?:\/\//.test(target)) {
    const { default: pg } = await import('pg');
    const local = /@(localhost|127\.0\.0\.1)[:/]/.test(target);
    const pool = new pg.Pool({
      connectionString: target,
      max: 3,
      // החיבור מוצפן. האישור של Supabase חתום ברשות פרטית שלהם ולכן אינו מאומת כאן.
      ssl: local ? false : { rejectUnauthorized: false },
    });
    pool.on('error', (e) => console.error('שגיאת חיבור למסד:', e.message));
    return {
      q: async (sql, params = []) => (await pool.query(sql, params)).rows,
      exec: (sql) => pool.query(sql),
      close: () => pool.end(),
    };
  }
  let PGlite;
  try {
    ({ PGlite } = await import('@electric-sql/pglite'));
  } catch {
    throw new Error('לא הוגדר DATABASE_URL, והמסד המקומי (PGlite) אינו מותקן. הריצי npm install.');
  }
  let dir;
  if (target !== ':memory:') {
    dir = target ?? resolve(here, '..', 'data', 'pgdata');
    mkdirSync(dirname(dir), { recursive: true });
  }
  const db = await PGlite.create(dir);
  return {
    q: async (sql, params = []) => (await db.query(sql, params)).rows,
    exec: (sql) => db.exec(sql),
    close: () => db.close(),
  };
}

export async function openLibrary(target = process.env.DATABASE_URL) {
  const { q, exec, close } = await connect(target);
  await exec(SCHEMA);

  // קטגוריות התחלתיות - רק בפעם הראשונה, כדי שמחיקה שלהן תישאר מחיקה.
  const seeded = await q(
    `INSERT INTO meta (key, value) VALUES ('seeded', '1') ON CONFLICT DO NOTHING RETURNING key`
  );
  if (seeded.length) {
    await q(
      'INSERT INTO categories (name) SELECT unnest($1::text[]) ON CONFLICT DO NOTHING',
      [DEFAULT_CATEGORIES]
    );
  }

  const bookKey = (title, author) => `${normalize(title)}|${normalize(author)}`;

  const lib = {
    close,

    // ---------- קטגוריות ----------
    listCategories() {
      return q(
        `SELECT c.id, c.name, COUNT(b.id)::int AS "bookCount"
         FROM categories c LEFT JOIN books b ON b.category_id = c.id
         GROUP BY c.id ORDER BY c.name`
      );
    },

    async findCategory(name) {
      const n = normalize(name);
      return (await lib.listCategories()).find((c) => normalize(c.name) === n) ?? null;
    },

    async addCategory(name) {
      const clean = cleanText(name, 'שם קטגוריה', { required: true, max: 60 });
      if (await lib.findCategory(clean)) throw new LibraryError('קטגוריה בשם הזה כבר קיימת', 409);
      const [row] = await q('INSERT INTO categories (name) VALUES ($1) RETURNING id', [clean]);
      return { id: row.id, name: clean, bookCount: 0 };
    },

    async renameCategory(id, name) {
      const clean = cleanText(name, 'שם קטגוריה', { required: true, max: 60 });
      const other = await lib.findCategory(clean);
      if (other && other.id !== Number(id)) {
        throw new LibraryError('קטגוריה בשם הזה כבר קיימת', 409);
      }
      const rows = await q('UPDATE categories SET name = $1 WHERE id = $2 RETURNING id', [clean, id]);
      if (!rows.length) throw new LibraryError('הקטגוריה לא נמצאה', 404);
    },

    /** מחיקת קטגוריה. הספרים שבה נשארים, בלי קטגוריה. */
    async deleteCategory(id) {
      const rows = await q('DELETE FROM categories WHERE id = $1 RETURNING id', [id]);
      if (!rows.length) throw new LibraryError('הקטגוריה לא נמצאה', 404);
    },

    /** מחזיר מזהה קטגוריה לפי שם, ויוצר אותה אם אינה קיימת. */
    async categoryIdByName(name) {
      const clean = cleanText(name, 'שם קטגוריה', { max: 60 });
      if (!clean) return null;
      return ((await lib.findCategory(clean)) ?? (await lib.addCategory(clean))).id;
    },

    // ---------- ספרים ----------
    listBooks() {
      return q(`${BOOK_SELECT} ORDER BY b.title, b.author, b.id`);
    },

    async getBook(id) {
      const [book] = await q(`${BOOK_SELECT} WHERE b.id = $1`, [id]);
      if (!book) throw new LibraryError('הספר לא נמצא', 404);
      return book;
    },

    /** בדיקת השדות הטקסטואליים של ספר (בלי גישה למסד). */
    _textFields(input) {
      const title = cleanText(input.title, 'שם הספר', { required: true });
      const author = cleanText(input.author, 'שם הסופר');
      const notes = cleanText(input.notes, 'הערות', { max: 1000 });
      const ageGroup = cleanText(input.ageGroup, 'גיל מומלץ');
      if (ageGroup && !AGE_GROUPS.includes(ageGroup)) {
        throw new LibraryError(`גיל מומלץ לא מוכר. האפשרויות: ${AGE_GROUPS.join(', ')}`);
      }
      return { title, author, notes, ageGroup };
    },

    async _bookFields(input) {
      const f = lib._textFields(input);
      let categoryId = null;
      if (input.categoryId != null && input.categoryId !== '') {
        categoryId = Number(input.categoryId);
        const found = Number.isInteger(categoryId)
          ? await q('SELECT 1 FROM categories WHERE id = $1', [categoryId])
          : [];
        if (!found.length) throw new LibraryError('הקטגוריה לא נמצאה', 404);
      } else if (input.category) {
        categoryId = await lib.categoryIdByName(input.category);
      }
      return { ...f, categoryId };
    },

    async addBook(input) {
      const f = await lib._bookFields(input);
      const [row] = await q(
        `INSERT INTO books (title, author, category_id, age_group, notes)
         VALUES ($1, $2, $3, $4, $5) RETURNING id`,
        [f.title, f.author, f.categoryId, f.ageGroup, f.notes]
      );
      return lib.getBook(row.id);
    },

    async updateBook(id, input) {
      await lib.getBook(id);
      const f = await lib._bookFields(input);
      await q(
        `UPDATE books SET title = $1, author = $2, category_id = $3, age_group = $4, notes = $5
         WHERE id = $6`,
        [f.title, f.author, f.categoryId, f.ageGroup, f.notes, id]
      );
      return lib.getBook(id);
    },

    async deleteBook(id) {
      const rows = await q('DELETE FROM books WHERE id = $1 RETURNING id', [id]);
      if (!rows.length) throw new LibraryError('הספר לא נמצא', 404);
    },

    /**
     * הוספה מרוכזת. כל שורה: שם הספר | סופר | קטגוריה | גיל מומלץ
     * (רק שם הספר חובה). ספר שכבר קיים עם אותו שם ואותו סופר - מדולג.
     * כל השורות התקינות נכנסות בפקודה אחת.
     */
    async importBooks(text) {
      const existing = new Set((await lib.listBooks()).map((b) => bookKey(b.title, b.author)));
      const result = { added: 0, skipped: 0, errors: [] };
      const rows = [];
      String(text ?? '')
        .split(/\r?\n/)
        .forEach((line, i) => {
          if (!line.trim()) return;
          const [title, author, category, ageGroup] = line.split(/[|\t]/).map((s) => s.trim());
          const key = bookKey(title, author);
          if (existing.has(key)) {
            result.skipped++;
            return;
          }
          try {
            const f = lib._textFields({ title, author, ageGroup });
            rows.push({ ...f, category: cleanText(category, 'שם קטגוריה', { max: 60 }) });
            existing.add(key);
          } catch (e) {
            if (!(e instanceof LibraryError)) throw e;
            result.errors.push(`שורה ${i + 1}: ${e.message}`);
          }
        });
      if (!rows.length) return result;

      const categoryIds = new Map();
      for (const name of new Set(rows.map((r) => r.category).filter(Boolean))) {
        categoryIds.set(name, await lib.categoryIdByName(name));
      }
      await q(
        `INSERT INTO books (title, author, category_id, age_group)
         SELECT * FROM unnest($1::text[], $2::text[], $3::int[], $4::text[])`,
        [
          rows.map((r) => r.title),
          rows.map((r) => r.author),
          rows.map((r) => categoryIds.get(r.category) ?? null),
          rows.map((r) => r.ageGroup),
        ]
      );
      result.added = rows.length;
      return result;
    },

    /**
     * חיפוש ספר לפי שם (ואופציונלית סופר). התאמה מדויקת גוברת על התאמה חלקית.
     */
    async findBooksByTitle(title, author) {
      const t = normalize(title);
      if (!t) return [];
      const a = normalize(author);
      let books = await lib.listBooks();
      if (a) books = books.filter((b) => normalize(b.author).includes(a));
      const exact = books.filter((b) => normalize(b.title) === t);
      if (exact.length) return exact;
      return books.filter((b) => normalize(b.title).includes(t));
    },

    // ---------- השאלות ----------
    async openLoan(bookId, borrower, date) {
      const book = await lib.getBook(bookId);
      const name = cleanText(borrower, 'שם המשאילה', { required: true, max: 100 });
      const loanedAt = cleanDate(date);
      const taken = (b) =>
        new LibraryError(`הספר "${b.title}" כבר מושאל ל${b.borrower} מתאריך ${b.loanedAt}`, 409);
      if (book.loanId) throw taken(book);
      try {
        await q('INSERT INTO loans (book_id, borrower, loaned_at) VALUES ($1, $2, $3)', [
          bookId,
          name,
          loanedAt,
        ]);
      } catch (e) {
        // שתי השאלות נפתחו באותו רגע - האינדקס הייחודי עצר את השנייה.
        if (e.code === '23505') throw taken(await lib.getBook(bookId));
        throw e;
      }
      return lib.getBook(bookId);
    },

    async closeLoan(bookId, date) {
      const book = await lib.getBook(bookId);
      if (!book.loanId) throw new LibraryError(`הספר "${book.title}" אינו מושאל כרגע`, 409);
      const returnedAt = cleanDate(date);
      if (returnedAt < book.loanedAt) {
        throw new LibraryError('תאריך ההחזרה מוקדם מתאריך ההשאלה');
      }
      await q('UPDATE loans SET returned_at = $1 WHERE id = $2', [returnedAt, book.loanId]);
      return {
        book: await lib.getBook(bookId),
        borrower: book.borrower,
        loanedAt: book.loanedAt,
        returnedAt,
      };
    },

    async loanHistory(bookId) {
      await lib.getBook(bookId);
      return q(
        `SELECT id, borrower, loaned_at AS "loanedAt", returned_at AS "returnedAt"
         FROM loans WHERE book_id = $1 ORDER BY loaned_at DESC, id DESC`,
        [bookId]
      );
    },

    /** שמות שכבר השאילו בעבר - להשלמה אוטומטית. */
    async listBorrowers() {
      const rows = await q('SELECT borrower FROM loans GROUP BY borrower ORDER BY MAX(id) DESC');
      return rows.map((r) => r.borrower);
    },
  };

  return lib;
}
